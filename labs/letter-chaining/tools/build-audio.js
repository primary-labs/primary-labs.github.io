#!/usr/bin/env node
/* Wraps each audio clip in assets/audio/ in a small .js file the page can load.
 *
 *   node tools/build-audio.js
 *
 * Why: the page's security policy (connect-src 'none') stops scripts from downloading files,
 * which is what keeps teacher recordings on the device. Scripts from this site are still allowed,
 * so each clip ships as assets/audio/<group>/<name>.js and plays through Web Audio, which works the
 * same in Chrome, Edge, Firefox, and Safari.
 *
 * Run this after adding or replacing any .wav or .mp3 file. If a clip has both, the .mp3 wins.
 */
'use strict';

var fs = require('fs');
var path = require('path');

var AUDIO = path.join(__dirname, '..', 'assets', 'audio');
var GROUPS = ['words', 'keywords', 'sentences'];
var TYPES = { '.wav': 'audio/wav', '.mp3': 'audio/mpeg' };

function build() {
  var count = 0;
  GROUPS.forEach(function (group) {
    var dir = path.join(AUDIO, group);
    if (!fs.existsSync(dir)) return;
    var files = fs.readdirSync(dir);
    var byName = {};
    files.forEach(function (f) {
      var ext = path.extname(f).toLowerCase();
      if (!TYPES[ext]) return;
      var name = path.basename(f, path.extname(f));
      if (byName[name] && byName[name] !== f) console.warn('Both ' + byName[name] + ' and ' + f + ' exist in ' + group + '/. Using the .mp3.');
      if (!byName[name] || ext === '.mp3') byName[name] = f;
    });
    // Remove wrappers whose clip is gone
    files.forEach(function (f) {
      if (path.extname(f) === '.js' && !byName[path.basename(f, '.js')]) fs.unlinkSync(path.join(dir, f));
    });
    Object.keys(byName).sort().forEach(function (name) {
      var file = byName[name];
      var data = fs.readFileSync(path.join(dir, file)).toString('base64');
      var js = '/* Generated by tools/build-audio.js from ' + group + '/' + file + '. Do not edit. */\n' +
        'window.PL.Sound.addClip(' + JSON.stringify(group + '/' + name) + ', ' +
        JSON.stringify(TYPES[path.extname(file).toLowerCase()]) + ', ' + JSON.stringify(data) + ');\n';
      fs.writeFileSync(path.join(dir, name + '.js'), js);
      count++;
    });
  });
  return count;
}

module.exports = build;

if (require.main === module) {
  console.log('Wrapped ' + build() + ' clips.');
}
