#!/usr/bin/env node
/* Wraps each clip in assets/audio/phrases/ in a small .js file the page can load.
 *
 *   node tools/build-audio.js
 *
 * Why: the page's security policy (connect-src 'none') stops scripts from downloading files.
 * Scripts from this site are still allowed, so each clip ships as assets/audio/phrases/<id>.js.
 * It also writes assets/audio/index.js, the list of clips that exist, so the page goes straight
 * to the device voice for anything without a clip instead of trying to load a missing file.
 *
 * Run this after adding or replacing any .wav or .mp3 file. If a clip has both, the .mp3 wins.
 */
'use strict';

var fs = require('fs');
var path = require('path');
var vm = require('vm');

var TYPES = { '.wav': 'audio/wav', '.mp3': 'audio/mpeg' };

function phraseIds() {
  var sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'js', 'phrases.js'), 'utf8'), sandbox);
  return new Set(sandbox.window.MM.Phrases.all().map(function (p) { return p.id; }));
}

function build(audioDir) {
  audioDir = audioDir || path.join(__dirname, '..', 'assets', 'audio');
  var dir = path.join(audioDir, 'phrases');
  var known = phraseIds();
  var files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  var byId = {};
  files.forEach(function (f) {
    var ext = path.extname(f).toLowerCase();
    if (!TYPES[ext]) return;
    var id = path.basename(f, path.extname(f));
    if (!known.has(id)) { console.warn('Skipping ' + f + ': no phrase has the id "' + id + '".'); return; }
    if (byId[id] && byId[id] !== f) console.warn('Both ' + byId[id] + ' and ' + f + ' exist. Using the .mp3.');
    if (!byId[id] || ext === '.mp3') byId[id] = f;
  });
  // Remove wrappers whose clip is gone
  files.forEach(function (f) {
    if (path.extname(f) === '.js' && !byId[path.basename(f, '.js')]) fs.unlinkSync(path.join(dir, f));
  });
  var ids = Object.keys(byId).sort();
  ids.forEach(function (id) {
    var file = byId[id];
    var data = fs.readFileSync(path.join(dir, file)).toString('base64');
    var js = '/* Generated by tools/build-audio.js from phrases/' + file + '. Do not edit. */\n' +
      'window.MM.Sound.addClip(' + JSON.stringify(id) + ', ' + JSON.stringify(TYPES[path.extname(file).toLowerCase()]) +
      ', ' + JSON.stringify(data) + ');\n';
    fs.writeFileSync(path.join(dir, id + '.js'), js);
  });
  fs.mkdirSync(audioDir, { recursive: true });
  fs.writeFileSync(path.join(audioDir, 'index.js'),
    '/* Generated by tools/build-audio.js: the phrases that have a clip. Do not edit. */\n' +
    'window.MM.Sound.setClips(' + JSON.stringify(ids) + ');\n');
  return ids.length;
}

module.exports = build;

if (require.main === module) {
  console.log('Wrapped ' + build() + ' clips.');
}
