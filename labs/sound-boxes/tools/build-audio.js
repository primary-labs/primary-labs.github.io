#!/usr/bin/env node
/* Wraps each clip in assets/audio/{sounds,words,phrases}/ in a small .js file the page can load.
 *
 *   node tools/build-audio.js
 *   node tools/build-audio.js --from <voice run>/af_heart/manifest.json
 *
 * Why: the page's security policy (connect-src 'none') stops scripts from downloading files.
 * Scripts from this site are still allowed, so each clip ships as assets/audio/<group>/<name>.js.
 * It also writes assets/audio/index.js, the list of clips that exist, so the page goes straight
 * to the device voice for anything without a clip instead of trying to load a missing file.
 *
 * --from records the text each direction's clip was made from (the voice tool's manifest.json) in
 * assets/audio/made-from.json, so the tests catch a direction that changed after its clip was made.
 *
 * Run this after copying clips (tools/copy-clips.js) or adding a direction's clip. If a clip has
 * both a .wav and an .mp3, the .mp3 wins.
 */
'use strict';

var fs = require('fs');
var path = require('path');
var load = require('./list-phrases').load;

var GROUPS = ['sounds', 'words', 'phrases'];
var TYPES = { '.wav': 'audio/wav', '.mp3': 'audio/mpeg' };

/* Keeps assets/audio/made-from.json (direction id → the text its clip says) for the clips that exist. */
function madeFrom(audioDir, ids, manifest) {
  var file = path.join(audioDir, 'made-from.json');
  var known = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
  if (manifest) JSON.parse(fs.readFileSync(manifest, 'utf8')).clips.forEach(function (c) { known[c.id] = c.text; });
  var out = {};
  ids.forEach(function (id) { if (known[id] !== undefined) out[id] = known[id]; });
  fs.writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
}

/* name → file for one group's clips; directions with no phrase are skipped. */
function clipsIn(dir, group, phraseIds) {
  var files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  var byName = {};
  files.forEach(function (f) {
    var ext = path.extname(f).toLowerCase();
    if (!TYPES[ext]) return;
    var name = path.basename(f, path.extname(f));
    if (group === 'phrases' && !phraseIds.has(name)) { console.warn('Skipping ' + f + ': no phrase has the id "' + name + '".'); return; }
    if (byName[name] && byName[name] !== f) console.warn('Both ' + byName[name] + ' and ' + f + ' exist. Using the .mp3.');
    if (!byName[name] || ext === '.mp3') byName[name] = f;
  });
  // Remove wrappers whose clip is gone
  files.forEach(function (f) {
    if (path.extname(f) === '.js' && !byName[path.basename(f, '.js')]) fs.unlinkSync(path.join(dir, f));
  });
  return byName;
}

function build(audioDir, manifest) {
  audioDir = audioDir || path.join(__dirname, '..', 'assets', 'audio');
  var phraseIds = new Set(load().Phrases.all().map(function (p) { return p.id; }));
  var ids = [], phrases = [];
  GROUPS.forEach(function (group) {
    var dir = path.join(audioDir, group);
    var byName = clipsIn(dir, group, phraseIds);
    Object.keys(byName).sort().forEach(function (name) {
      var file = byName[name], id = group + '/' + name;
      var data = fs.readFileSync(path.join(dir, file)).toString('base64');
      var js = '/* Generated by tools/build-audio.js from ' + group + '/' + file + '. Do not edit. */\n' +
        'window.SB.Sound.addClip(' + JSON.stringify(id) + ', ' + JSON.stringify(TYPES[path.extname(file).toLowerCase()]) +
        ', ' + JSON.stringify(data) + ');\n';
      fs.writeFileSync(path.join(dir, name + '.js'), js);
      ids.push(id);
      if (group === 'phrases') phrases.push(name);
    });
  });
  fs.mkdirSync(audioDir, { recursive: true });
  fs.writeFileSync(path.join(audioDir, 'index.js'),
    '/* Generated by tools/build-audio.js: the clips that exist. Do not edit. */\n' +
    'window.SB.Sound.setClips(' + JSON.stringify(ids) + ');\n');
  madeFrom(audioDir, phrases, manifest);
  return ids.length;
}

module.exports = build;

if (require.main === module) {
  var at = process.argv.indexOf('--from');
  console.log('Wrapped ' + build(null, at > -1 ? process.argv[at + 1] : null) + ' clips.');
}
